/** Placeholders in a base URL, e.g. ["ACCOUNT_ID"] for "https://…/{ACCOUNT_ID}/ai/v1". */
export const urlFields = (entry) => [...new Set([...(entry.baseUrl || '').matchAll(/\{([A-Z_]+)\}/g)].map((m) => m[1]))];

/** A provider config entry built from a catalog entry. */
export function providerFromCatalog(id, extra = {}) {
  const e = CATALOG[id];
  if (!e) throw new Error(`unknown catalog provider "${id}"`);
  const p = { type: e.type || 'openai', enabled: false, catalog: id, baseUrl: e.baseUrl, apiKeyEnv: e.apiKeyEnv, model: e.model || '' };
  if (e.apiKeyOptional) p.apiKeyOptional = true;
  if (e.category === 'local') p.free = true;
  return { ...p, ...extra };
}

/** The built-in provider defaults that come from the catalog. */
export function catalogDefaults() {
  return Object.fromEntries(Object.entries(BUILTIN_ALIASES).map(([name, [id, extra]]) => [name, providerFromCatalog(id, extra)]));
}
